import { generateInterviewReport, generateResumePdf} from "../services/ai.service.js";
import {PDFParse} from 'pdf-parse'
import interviewReportModel from "../models/report.model.js";
import mongoose from "mongoose";
// import { selfDescription } from "../services/temp.js";

async function genReportController(req,res){
    try {
        if (!req.file) {
            return res.status(400).json({ message: "Resume file is required" });
        }

        const fileName = req.file.originalname || ""
        const mimeType = req.file.mimetype || ""
        const isPdf = mimeType === "application/pdf" || fileName.toLowerCase().endsWith(".pdf")

        if (!isPdf) {
            return res.status(400).json({
                message: "Only PDF resumes are supported right now. Please upload a PDF file."
            })
        }

        const parser = new PDFParse({
            data: new Uint8Array(req.file.buffer)
        });

        const pdfText = await parser.getText();
        const resumeContent = pdfText.text;
        const { jobDescription, selfDescription } = req.body;

        const interviewReportByAi = await generateInterviewReport({
            resume: resumeContent,
            jobDescription,
            selfDescription
        });

        const interviewReport = await interviewReportModel.create({
            user: req.user.id,
            resume: resumeContent,
            selfDescription,
            jobDescription,
            title: interviewReportByAi.title || "Interview Report",
            ...interviewReportByAi
        });

        return res.status(201).json({
            message: "Interview report generated by AI successfully",
            interviewReport
        });
    } catch (error) {
        console.error("genReportController error:", error);

        const errorMessage = error?.message || "";
        const isAiUnavailable =
            errorMessage.includes('"code":503') ||
            errorMessage.includes("high demand") ||
            errorMessage.includes("UNAVAILABLE") ||
            error?.status === 503 ||
            error?.statusCode === 503;

        if (isAiUnavailable) {
            return res.status(503).json({
                success: false,
                message: "The AI service is currently busy. Please wait a moment and try generating your report again."
            });
        }

        return res.status(500).json({
            success: false,
            message: "Failed to generate interview report. Please try again.",
            error: error.message
        });
    }
}

async function getReportByIdController(req,res){
    const {interviewId}=req.params;

    if (!mongoose.isValidObjectId(interviewId)) {
        return res.status(404).json({
            message:"Interview report not found"
        })
    }

    const interviewReport= await interviewReportModel.findOne({_id:interviewId,user:req.user.id})

    if(!interviewReport){
        return res.status(404).json({
            message:"Interview report not found"
        })
    }

    res.status(200).json({
        message:"Interview report fetch successfully",
        interviewReport
    })

}

async function getAllInterviewReportsController(req,res){
    const interviewReports = await interviewReportModel.find({ user: req.user.id }).sort({ createdAt: -1 }).select("-resume -selfDescription -jobDescription -__v -technicalQuestions -behavioralQuestions -skillGaps -preparationPlan")

    res.status(200).json({
        message: "Interview reports fetched successfully.",
        interviewReports
    })
}

async function generateResumePdfController(req, res) {
   const { interviewId } = req.params

    const interviewReport = await interviewReportModel.findById(interviewId)

    if (!interviewReport) {
        return res.status(404).json({
            message: "Interview report not found."
        })
    }

    const {resume,selfDescription,jobDescription} = interviewReport

    const pdfBuffer= await generateResumePdf({resume,selfDescription,jobDescription })

     res.set({
        "Content-Type": "application/pdf",
        "Content-Disposition": `attachment; filename=resume_${interviewId}.pdf`
    })  

     res.send(pdfBuffer)

}

export default {genReportController,getReportByIdController,getAllInterviewReportsController, generateResumePdfController}